// Finding your way in the game code.
//   node tools/map.cjs <name>   every line that DEFINES or REPLACES (wraps) a global, in load order. Many functions are wrapped by later
//                               files ({const S0=step;step=()=>{...S0()...}}): the LAST wrapper listed runs first, the first line is the base.
//   node tools/map.cjs          regenerates PROJECT_MAP.md (every file, in load order, with its header comment)
const fs = require('fs'), path = require('path'); const { scripts } = require('./headless.cjs');
const ROOT = path.join(__dirname, '..'), files = scripts().filter(f => !f.startsWith('src/data/'));
const n = process.argv[2];
if (n) {
  const e = n.replace(/[$]/g, '\\$'), def = new RegExp(`(^|[^.\\w])(function ${e}\\(|(const|let|var) ([\\w,]*,)?${e}\\b|${e}\\s*=(?![=>]))`), any = new RegExp(`\\b${e}\\b`);
  let hits = 0, uses = 0;
  for (const f of files) fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').forEach((l, i) => {
    if (def.test(l)) { hits++; const k = Math.max(0, l.search(def)); console.log(`${f}:${i + 1}  ${l.slice(Math.max(0, k - 40), k + 120).trim()}`); } else if (any.test(l)) uses++;
  });
  console.log(`${hits} definition/wrapper lines, ${uses} other lines use "${n}"`);
} else {
  const head = f => { const l = fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').find(x => /^\/\/|^\/\*\*/.test(x)) || ''; return l.replace(/^\/\/\s*[=-]*\s*|^\/\*\*\s*/, '').replace(/\*\/$/, '').replace(/\s*=+\s*$/, '').slice(0, 150); };
  let out = '# PROJECT_MAP (generated by `node tools/map.cjs`, do not edit)\n\nFiles in LOAD ORDER (= index.html). Folder = theme. The order matters: a later file can wrap (replace) a function of an earlier one.\n';
  let cur = '';
  for (const f of files) { const d = path.dirname(f); if (d !== cur) { cur = d; } out += `- \`${f}\` ${head(f)}\n`; }
  fs.writeFileSync(path.join(ROOT, 'PROJECT_MAP.md'), out); console.log('PROJECT_MAP.md:', files.length, 'files');
}
